# Regenerates the AI photos (Higgsfield, GPT Image 2.6 Sunburst, Unlimited mode, 27 Nov 2026; see docs/EQUIPMENT_IMAGES.md).
# Input: the original PNGs in assets/photos/src/<key>.png (keys: home, stove, flattop, oven, warmer, pizza, prep, fryer, rack, fridge).
# Output: assets/photos/<key>.jpg (web copies kept in the repo) and photoData.generated.ts (data URIs the bundle uses;
# webpack here has no emitting loader and jest has no asset transform, so images are inlined).
# Usage: python3 gen_photos.py
import base64, io, os
from PIL import Image

D = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(D, 'photos', 'src')
OUT = os.path.join(D, 'photos')
# Equipment tiles render at most ~160 CSS px wide (320 px on 2x screens); the Home photo spans the page.
SIZES = {'home': (1440, 230 * 1024)}
DEFAULT = (480, 40 * 1024)

def encode(im, max_side, budget):
    im = im.copy(); im.thumbnail((max_side, max_side), Image.LANCZOS)
    for q in (82, 76, 70, 64, 58):
        b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True, progressive=True)
        if b.tell() <= budget: break
    return im.size, q, b.getvalue()

lines = ['// Generated by gen_photos.py. Do not edit. AI-generated photos (not the client\'s real equipment); see docs/EQUIPMENT_IMAGES.md.', 'export const PHOTOS: Record<string, string> = {']
for name in sorted(os.listdir(SRC)):
    key, ext = os.path.splitext(name)
    if ext.lower() not in ('.png', '.jpg', '.jpeg', '.webp'): continue
    im = Image.open(os.path.join(SRC, name)).convert('RGB')
    max_side, budget = SIZES.get(key, DEFAULT)
    size, q, data = encode(im, max_side, budget)
    open(os.path.join(OUT, key + '.jpg'), 'wb').write(data)
    lines.append(f"  '{key}': 'data:image/jpeg;base64,{base64.b64encode(data).decode()}',")
    print(key, size, 'q', q, len(data) // 1024, 'KB')
lines.append('};')
open(os.path.join(D, 'photoData.generated.ts'), 'w').write('\n'.join(lines) + '\n')
