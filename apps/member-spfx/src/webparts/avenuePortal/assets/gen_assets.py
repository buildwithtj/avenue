# Regenerates dining-room.jpg and imageData.generated.ts from the client's public website photo.
# Source: https://flavorsculinaryhub.com/wp-content/uploads/2024/06/Flavors-slider-image.jpg (download it, pass the path).
# Usage: python3 gen_assets.py <source.jpg>
import sys, base64, io, os
from PIL import Image
d = os.path.dirname(os.path.abspath(__file__))
im = Image.open(sys.argv[1]).convert('RGB'); im.thumbnail((960, 960))
for q in (72, 66, 60):
    b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True, progressive=True)
    if b.tell() <= 90 * 1024: break
open(f'{d}/dining-room.jpg', 'wb').write(b.getvalue())
open(f'{d}/imageData.generated.ts', 'w').write(
  '// Generated by gen_assets.py. Do not edit. Images are inlined as data URIs (see docs/EQUIPMENT_IMAGES.md).\n'
  f"export const DINING_ROOM = 'data:image/jpeg;base64,{base64.b64encode(b.getvalue()).decode()}';\n")
print(im.size, q, b.tell())
