# Builds the one-line "Flavors Culinary Hub" wordmark as SVG outlines (no font file ships; text is drawn as paths).
# "Flavors": Playfair Display (SIL OFL 1.1, fonts/PLAYFAIR-LICENSE.txt), weight 700. "CULINARY HUB": Inter (SIL OFL 1.1), weight 600, tracked.
# Usage: python3 gen_logo.py <PlayfairDisplay[wght].ttf>   -> logo.generated.ts and logo-preview.svg
# This is a [PROPOSED] wordmark made by the developer; the client has not supplied or approved a logo.
import io, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

D = os.path.dirname(os.path.abspath(__file__))

def load(path, wght):
    f = TTFont(path)
    if 'fvar' in f: f = instantiateVariableFont(f, {'wght': wght})
    return f

def run(font, text, size, x0, baseline, tracking=0.0):
    """Outline `text` at `size` px with its baseline at `baseline`; returns (svg path d, advance end x, bounds)."""
    upm = font['head'].unitsPerEm; s = size / upm
    cmap = font.getBestCmap(); gs = font.getGlyphSet(); hmtx = font['hmtx']
    pen = SVGPathPen(gs); bp = BoundsPen(gs); x = x0
    for ch in text:
        g = cmap.get(ord(ch))
        if g is None: continue
        t = (s, 0, 0, -s, x, baseline)
        gs[g].draw(TransformPen(pen, t)); gs[g].draw(TransformPen(bp, t))
        x += hmtx[g][0] * s + tracking * size
    return pen.getCommands(), x - tracking * size, bp.bounds

serif = load(sys.argv[1], 700)
sans = load(os.path.join(D, 'fonts', 'inter-latin-wght.woff2'), 600)

BASE = 40.0
d1, x1, b1 = run(serif, 'Flavors', 44, 0, BASE)
gap = 14
dot_cx = x1 + gap; dot_r = 3.2
d2, x2, b2 = run(sans, 'CULINARY HUB', 15, dot_cx + gap, BASE - 1, tracking=0.16)
top = min(b1[1], b2[1]) - 1; bottom = max(b1[3], b2[3]) + 1
w = x2 + 1; h = bottom - top
# x-height middle of the serif line, for the separator dot
dot_cy = BASE - 15 * 0.36 - 1

vb = f'0 {top:.1f} {w:.1f} {h:.1f}'
ts = ('// Generated by gen_logo.py. Do not edit. [PROPOSED] wordmark for Flavors Culinary Hub (Playfair Display + Inter, both SIL OFL 1.1).\n'
      f"export const LOGO_VIEWBOX = '{vb}';\n"
      f"export const LOGO_RATIO = {w / h:.4f};\n"
      f"export const LOGO_SERIF = '{d1}';\n"
      f"export const LOGO_SANS = '{d2}';\n"
      f"export const LOGO_DOT = {{ cx: {dot_cx:.1f}, cy: {dot_cy:.1f}, r: {dot_r} }};\n")
open(os.path.join(D, 'logo.generated.ts'), 'w').write(ts)
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" height="200" style="background:#f4f6f7">'
       f'<path d="{d1}" fill="#0f4c5c"/><circle cx="{dot_cx:.1f}" cy="{dot_cy:.1f}" r="{dot_r}" fill="#C9A24D"/>'
       f'<path d="{d2}" fill="#4b5563"/></svg>')
open(os.path.join(D, 'logo-preview.svg'), 'w').write(svg)
print('viewBox', vb, 'ratio', round(w / h, 2), 'bytes', len(ts))
