// Reads ../../release/release.json and writes src/avenue/release.generated.ts (the modules compiled into this build).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const f = new URL('../../../release/release.json', import.meta.url);
const modules = existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')).modules : undefined;
writeFileSync(new URL('../src/avenue/release.generated.ts', import.meta.url),
  `// Generated by scripts/release.mjs from release/release.json. Do not edit.\nexport const RELEASE_MODULES: string[] | undefined = ${JSON.stringify(modules)};\n`);
